#!/usr/bin/env python3
"""Create ~/printer_data/gcodes/ss_bench_demo.gcode ON THE PI (bench v2 only: fake heaters, no motors).
Run: scripts/pi.sh 'python3 -' < scripts/make_bench_print.py
- Thumbnail copied from a real OrcaSlicer file on the printer (so the UI shows a real preview)
- 4 labelled objects (EXCLUDE_OBJECT_DEFINE) at real bed positions → cancel-object map
- SET_PRINT_STATS_INFO layers, ~3 minutes of dwell "printing"
"""
import glob, os, re

G = os.path.expanduser("~/printer_data/gcodes")
src = next((f for f in sorted(glob.glob(G + "/Tire-Monkey*.gcode"))), None)
thumb = ""
if src:
    with open(src, errors="ignore") as f:
        head = f.read(400000)
    blocks = re.findall(r"(; thumbnail begin .*?; thumbnail end\n)", head, re.S)
    thumb = "".join(blocks)
objs = [("handle_1", [(20, 30), (90, 30), (90, 50), (20, 50)]),
        ("handle_2", [(20, 70), (90, 70), (90, 90), (20, 90)]),
        ("handle_3", [(20, 110), (90, 110), (90, 130), (20, 130)]),
        ("cable_clip", [(115, 65), (155, 65), (155, 105), (115, 105)])]
layers = 40
out = ["; StarStack bench demo print: fake heaters, no motors. Safe on bench config v2.x only.",
       "; generated by klipper-ui/scripts/make_bench_print.py", thumb.rstrip("\n"),
       "; filament_type = PETG", "; estimated printing time (normal mode) = 3m 0s"]
for name, poly in objs:
    cx = sum(p[0] for p in poly) / 4
    cy = sum(p[1] for p in poly) / 4
    pts = ",".join(f"[{x},{y}]" for x, y in poly)
    out.append(f"EXCLUDE_OBJECT_DEFINE NAME={name} CENTER={cx:.1f},{cy:.1f} POLYGON=[{pts}]")
out += ["M104 S240", "M140 S80", "G28", f"SET_PRINT_STATS_INFO TOTAL_LAYER={layers}"]
for layer in range(1, layers + 1):
    out.append(f"SET_PRINT_STATS_INFO CURRENT_LAYER={layer}")
    for name, _ in objs:
        out += [f"EXCLUDE_OBJECT_START NAME={name}", "G4 P1100", f"EXCLUDE_OBJECT_END NAME={name}"]
out += ["M104 S0", "M140 S0"]
path = os.path.join(G, "ss_bench_demo.gcode")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print(f"wrote {path}: {len(out)} lines, thumbnail {'from ' + os.path.basename(src) if thumb else 'none'}")
